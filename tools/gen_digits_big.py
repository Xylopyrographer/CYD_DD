# -*- coding: utf-8 -*-
"""
Big proportional digit font for the TECH clock (round 3 — anti-aliased).
- Vector stroke skeletons rendered at 2x then LANCZOS-downsampled to
  cap height 92px -> smooth grayscale edges
- Quantized to TWO 1-bit masks: dim (edge) + bright (core)
- Device draws dim runs first, then bright runs — 2-level AA with plain
  drawFastHLine only (the rendering path proven solid on this panel)

Outputs: include/digits_font.h, tools/digits_glyphs.json, tools/digits_preview.png
"""
from PIL import Image, ImageDraw
import os, math, json, base64

HERE  = os.path.dirname(os.path.abspath(__file__))
OUT_H = os.path.join(HERE, "..", "include", "digits_font.h")
OUT_J = os.path.join(HERE, "digits_glyphs.json")
OUT_P = os.path.join(HERE, "digits_preview.png")

S     = 86 / 74.0        # skeleton scale (cap 86px)
W, H  = 44, 86
T     = 16
CX    = W / 2

def arc(cx, cy, rx, ry, a0, a1, deg_step=6):
    pts = []
    n = max(2, int(abs(a1 - a0) / deg_step) + 1)
    for i in range(n + 1):
        t = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(t), cy + ry * math.sin(t)))
    return pts

def poly(*pts):
    return list(pts)

G = {}
G['0'] = [arc(CX, H/2, 13*S, 30.5*S, 0, 360, 8)]
G['1'] = [poly((13.5*S, 15.5*S), (25.5*S, 7.5*S), (25.5*S, 66.5*S))]
G['2'] = [arc(CX, 23*S, 12.5*S, 16.5*S, 180, 368) +
          [(31.5*S, 27.9*S), (7.5*S, 60*S), (CX + 12.5*S, 67.5*S)]]
G['3'] = [poly((10.5*S, 8.5*S)) + arc(18*S, 21.5*S, 13*S, 13.5*S, 215, 450) +
          arc(18*S, 52.5*S, 14*S, 15*S, 270, 505)]
G['4'] = [poly((26.5*S, 6.5*S), (6.5*S, 43.5*S), (31.5*S, 43.5*S)),
          poly((26.5*S, 13*S), (26.5*S, 67.5*S))]
G['5'] = [poly((31.5*S, 6.5*S), (12*S, 6.5*S), (10.5*S, 37.5*S)) +
          arc(18*S, 51.5*S, 13.5*S, 16*S, 185, 450)]
G['6'] = [arc(19*S, 25*S, 9.5*S, 19.5*S, 355, 180) +
          arc(19*S, 53*S, 12.5*S, 14.5*S, 180, 520)]
G['7'] = [poly((6.5*S, 6.5*S), (31.5*S, 6.5*S), (11.5*S, 67.5*S))]
G['8'] = [arc(CX, 20.5*S, 13*S, 14*S, 0, 360, 8),
          arc(CX, 53.5*S, 14*S, 14.5*S, 0, 360, 8)]
G['9'] = [arc(CX, 21*S, 12.5*S, 14.5*S, 0, 360, 8) +
          arc(CX, 21*S, 12.5*S, 14.5*S, 0, 120)[1:] +
          [(31.2*S, 33*S), (31.2*S, 58*S)] + arc(24*S, 67.5*S, 7.2*S, 7.2*S, 270, 180)]

def glyph_gray(ch):
    """Render at 2x, downsample -> anti-aliased grayscale (0..255)."""
    big = Image.new("L", (W * 2, H * 2), 0)
    d = ImageDraw.Draw(big)
    for pl in G[ch]:
        pts = [(x * 2, y * 2) for x, y in pl]
        for i in range(len(pts) - 1):
            x0, y0 = pts[i]; x1, y1 = pts[i + 1]
            d.line([x0, y0, x1, y1], fill=255, width=int(T * 2))
            r = T
            for px, py in ((x0, y0), (x1, y1)):
                d.ellipse([px - r, py - r, px + r, py + r], fill=255)
    return big.resize((W, H), Image.LANCZOS)

COLW = 16
def colon_gray():
    big = Image.new("L", (COLW * 2, H * 2), 0)
    d = ImageDraw.Draw(big)
    for cy in (int(H * 0.30) * 2, int(H * 0.72) * 2):
        d.ellipse([COLW - 16, cy - 16, COLW + 16, cy + 16], fill=255)
    return big.resize((COLW, H), Image.LANCZOS)

glyphs = {ch: glyph_gray(ch) for ch in "0123456789"}
glyphs[":"] = colon_gray()

def pack_mask(img, thresh):
    """1-bit rows: bit set where grayscale >= thresh."""
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        cur, nbits, acc = 0, 0, []
        for x in range(w):
            cur = (cur << 1) | (1 if px[x, y] >= thresh else 0)
            nbits += 1
            if nbits == 8:
                acc.append(cur); cur = 0; nbits = 0
        if nbits:
            acc.append(cur << (8 - nbits))
        rows.extend(acc)
    return rows

DIM_T, BRIGHT_T = 70, 170      # grayscale thresholds for the two masks
order = list("0123456789:")
data = {}
for ch in order:
    data[ch] = {"w": glyphs[ch].width,
                "rows": pack_mask(glyphs[ch], DIM_T),
                "rowsHi": pack_mask(glyphs[ch], BRIGHT_T)}
offs, blob, blobHi, off = {}, [], [], 0
for ch in order:
    offs[ch] = off
    blob.extend(data[ch]["rows"])
    blobHi.extend(data[ch]["rowsHi"])
    off += len(data[ch]["rows"])

lines = ["#pragma once",
         "// Auto-generated by tools/gen_digits_big.py — round-stroke digits,",
         "// 2x supersampled + downsampled, TWO masks for 2-level anti-aliasing:",
         "//   digitBits   = dim edge mask  (draw first, half-brightness colour)",
         "//   digitBitsHi = bright core mask (draw second, full colour)",
         f"// cap height {H} px. 1-bit rows, MSB first.",
         "#include <pgmspace.h>", "",
         f"#define DIGIT_GLYPH_H   {H}",
         f"#define DIGIT_ROW_BYTES {(W + 7) // 8}", "",
         "static const uint8_t digitW[10] PROGMEM = { " +
         ", ".join(str(data[ch]["w"]) for ch in "0123456789") + " };",
         "static const uint16_t digitOff[11] PROGMEM = { " +
         ", ".join(str(offs[ch]) for ch in order) + " };",
         f"#define DIGIT_BLOB_LEN {len(blob)}",
         "static const uint8_t digitBits[DIGIT_BLOB_LEN] PROGMEM = {"]
for i in range(0, len(blob), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in blob[i:i + 16]) + ",")
lines.append("};")
lines.append("static const uint8_t digitBitsHi[DIGIT_BLOB_LEN] PROGMEM = {")
for i in range(0, len(blobHi), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in blobHi[i:i + 16]) + ",")
lines.append("};")
with open(OUT_H, "w") as f:
    f.write("\n".join(lines) + "\n")

with open(OUT_J, "w") as f:
    json.dump({ch: {"w": data[ch]["w"],
                    "rows": base64.b64encode(bytes(data[ch]["rows"])).decode(),
                    "rowsHi": base64.b64encode(bytes(data[ch]["rowsHi"])).decode()}
               for ch in order}, f)

def compose(s, gap=3, cgap=2):
    total = 0
    prev = False
    for i, c in enumerate(s):
        if i: total += cgap if (c == ':' or prev) else gap
        total += glyphs[c].width
        prev = (c == ':')
    img = Image.new("L", (total + 20, H + 20), 0)
    x = 10
    prev = False
    for i, c in enumerate(s):
        if i: x += cgap if (c == ':' or prev) else gap
        img.paste(glyphs[c], (x, 10), glyphs[c])
        x += glyphs[c].width
        prev = (c == ':')
    return img

prev = Image.new("L", (460, 2 * (H + 30)), 0)
prev.paste(compose("22:11"), (10, 10))
prev.paste(compose("21:38"), (10, H + 30))
prev.save(OUT_P)
print("'22:11' ink width:", compose("22:11").width - 20)
print("saved:", OUT_H)
print("saved:", OUT_J)
print("saved:", OUT_P)
