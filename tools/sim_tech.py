# -*- coding: utf-8 -*-
"""
TECH theme simulator (round 2) — renders the PROPOSED new layout with the
big 92px digit font next to the mockup, using the exact bitmaps the firmware
will draw (tools/digits_glyphs.json, generated by tools/gen_digits_big.py).
"""
from PIL import Image, ImageDraw, ImageFont
import os, json, base64

HERE  = os.path.dirname(os.path.abspath(__file__))
W, H  = 320, 240
BG      = (0, 0, 0)
CARD    = (0x1B, 0x1E, 0x22)
BORDER  = (0x3A, 0x40, 0x46)
GRAY    = (0x8A, 0x93, 0x9B)
WHITE   = (0xF2, 0xF5, 0xF7)
CYAN    = (0x2B, 0xD9, 0xE8)

with open(os.path.join(HERE, "digits_glyphs.json")) as f:
    _gd = json.load(f)
GLYPHS = {ch: {"w": v["w"], "rb": (v["w"] + 7) // 8,
               "rows": base64.b64decode(v["rows"]),
               "rowsHi": base64.b64decode(v["rowsHi"])} for ch, v in _gd.items()}
DIG_H, DIG_GAP, COLON_INK, COLON_GAP = 86, 3, 16, 2
DIM = (0x6B, 0x6B, 0x6B)

f_label  = ImageFont.truetype(r"C:\Windows\Fonts\segoeui.ttf", 8)
f_temp   = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 33)
f_sec    = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 25)
f_date   = ImageFont.truetype(r"C:\Windows\Fonts\msyh.ttc", 16)
f_cjk_s  = ImageFont.truetype(r"C:\Windows\Fonts\msyh.ttc", 12)

TIME_CX, TIME_CY = 208, 75
SEC_CX,  SEC_CY  = 208, 143
DATE_CX, DATE_CY = 208, 173

def text_mc(d, s, font, cx, cy, fill):
    l, t_, r, b = font.getbbox(s)
    d.text((cx - (r - l) // 2 - l, cy - (b - t_) // 2 - t_), s, font=font, fill=fill)

def draw_big_digits(d, s, cx, cy, color):
    total = 0
    prev = False
    for i, ch in enumerate(s):
        isc = (ch == ':')
        if i: total += COLON_GAP if (isc or prev) else DIG_GAP
        total += COLON_INK if isc else GLYPHS[ch]["w"]
        prev = isc
    x = cx - total // 2
    y = cy - DIG_H // 2
    prev = False
    for i, ch in enumerate(s):
        isc = (ch == ':')
        if i: x += COLON_GAP if (isc or prev) else DIG_GAP
        if isc:
            for cy_ in (int(DIG_H * 0.30), int(DIG_H * 0.72)):
                d.ellipse([x + COLON_INK // 2 - 7, y + cy_ - 7,
                           x + COLON_INK // 2 + 7, y + cy_ + 7], fill=color)
            x += COLON_INK
        else:
            g = GLYPHS[ch]
            for pass_, (mask, col) in enumerate((
                    ("rows", DIM), ("rowsHi", color))):
                for r_ in range(DIG_H):
                    run = -1
                    for c_ in range(g["w"]):
                        byte = g[mask][r_ * g["rb"] + (c_ >> 3)]
                        bit = (byte >> (7 - (c_ & 7))) & 1
                        if bit and run < 0: run = c_
                        elif not bit and run >= 0:
                            d.line([x + run, y + r_, x + c_ - 1, y + r_], fill=col)
                            run = -1
                    if run >= 0:
                        d.line([x + run, y + r_, x + g["w"] - 1, y + r_], fill=col)
            x += g["w"]
        prev = isc

def card(d, x, y, w, h):
    d.rounded_rectangle([x, y, x + w, y + h], 8, fill=CARD, outline=BORDER, width=1)

def simulate():
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    d.line([282, 12, 309, 12], fill=CYAN, width=2)

    # original cards (unchanged from current firmware)
    card(d, 6, 8, 94, 62)
    d.text((14, 14), "TEMP", font=f_label, fill=GRAY)
    text_mc(d, "22", f_temp, 46, 40, WHITE)
    d.ellipse([60, 30, 68, 38], outline=WHITE, width=2)
    d.line([16, 64, 77, 64], fill=CYAN, width=2)

    card(d, 6, 78, 94, 78)
    d.text((14, 84), "WEATHER", font=f_label, fill=GRAY)
    d.ellipse([38, 96, 62, 120], outline=(200, 205, 210), width=3)
    text_mc(d, "多云", f_cjk_s, 53, 138, WHITE)

    card(d, 6, 164, 94, 68)
    d.line([8, 166, 97, 166], fill=CYAN, width=2)
    d.text((14, 170), "ENV", font=f_label, fill=GRAY)
    d.line([52, 186, 52, 226], fill=BORDER, width=1)
    text_mc(d, "湿度", f_cjk_s, 29, 192, GRAY)
    text_mc(d, "风速", f_cjk_s, 76, 192, GRAY)
    text_mc(d, "88%", f_cjk_s, 29, 212, WHITE)
    text_mc(d, "5.2m/s", f_cjk_s, 76, 212, WHITE)

    # firmware clear rect for the time area (drawn AFTER cards every minute
    # redraw — reproduces what the device actually does)
    d.rectangle([104, 22, 104 + 208 - 1, 22 + 108 - 1], fill=BG)

    # NEW big clock
    draw_big_digits(d, "22:11", TIME_CX, TIME_CY, WHITE)
    text_mc(d, "16", f_sec, SEC_CX, SEC_CY, CYAN)
    text_mc(d, "2026-11-10 周二", f_date, DATE_CX, DATE_CY, WHITE)
    return img

mock_path = os.path.join(HERE, "..", "doc", "ui_designs",
                         "ESP32_TFT_桌面时钟设备屏幕界面_UI_设计稿_32_2026-11-03T11-09-44.png")
mock = Image.open(mock_path).convert("RGB").resize((W, H), Image.LANCZOS)
combo = Image.new("RGB", (W * 2 + 8, H), (30, 30, 30))
combo.paste(simulate(), (0, 0))
combo.paste(mock, (W + 8, 0))
out = os.path.join(HERE, "sim_tech.png")
combo.save(out)
print("saved:", out)
